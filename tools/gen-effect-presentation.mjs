#!/usr/bin/env node
/**
 * The shared effect presentation table, as a module for Soundshed Guitar's web UI.
 *
 * How each effect and category looks (FX library colours and names, icons, the chain node's
 * colour class, the effect view's background and stock artwork) lives in one data file,
 * core/ui/data/effect-presentation.json. Soundshed Guitar Nano reads it at run time
 * (core/src/uiclient/EffectPresentation.cpp). The web UI is plain ES modules with no bundler,
 * so this writes the same data as typed constants to core/ui/ts/generated/effectPresentation.ts,
 * keying each effect by its EffectGuids constant. Both UIs then show an effect the same way.
 * tools/check-effect-presentation.mjs checks the data itself and that this module is current.
 *
 *   node tools/gen-effect-presentation.mjs          # regenerate
 *   node tools/gen-effect-presentation.mjs --check  # fail if the module is out of date (CI)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DATA = path.join(ROOT, 'core', 'ui', 'data', 'effect-presentation.json');
export const OUT = path.join(ROOT, 'core', 'ui', 'ts', 'generated', 'effectPresentation.ts');

export function readPresentation() {
  return JSON.parse(fs.readFileSync(DATA, 'utf8'));
}

const str = (value) => JSON.stringify(value);

/** `{ "key": "value", ... }` over several lines, keys in the file's order. */
function stringMap(map, indent = '  ') {
  const entries = Object.entries(map ?? {});
  if (entries.length === 0) return '{}';
  return `{\n${entries.map(([key, value]) => `${indent}${str(key)}: ${str(value)},`).join('\n')}\n}`;
}

function category(entry) {
  const fields = [`name: ${str(entry.name)}`, `color: ${str(entry.color)}`, `icon: ${str(entry.icon)}`];
  if (Array.isArray(entry.visualBackground)) fields.push(`visualBackground: [${str(entry.visualBackground[0])}, ${str(entry.visualBackground[1])}]`);
  if (entry.equipmentImage) fields.push(`equipmentImage: ${str(entry.equipmentImage)}`);
  return `{ ${fields.join(', ')} }`;
}

function effect(entry) {
  const fields = [];
  if (entry.icon) fields.push(`icon: ${str(entry.icon)}`);
  if (entry.equipmentImage) fields.push(`equipmentImage: ${str(entry.equipmentImage)}`);
  return `{ ${fields.join(', ')} }`;
}

/** Every icon the table names, for the IconKey check in iconAssets.ts. */
function iconNames(doc) {
  const names = new Set([doc.defaultIcon]);
  for (const entry of Object.values(doc.categories ?? {})) if (entry.icon) names.add(entry.icon);
  for (const entry of Object.values(doc.effects ?? {})) if (entry.icon) names.add(entry.icon);
  return [...names].sort();
}

export function generate(doc = readPresentation()) {
  const lines = [
    '// Generated by tools/gen-effect-presentation.mjs from core/ui/data/effect-presentation.json - do not edit by hand.',
    '// Regenerate with: node tools/gen-effect-presentation.mjs',
    '// Soundshed Guitar Nano reads the same file (core/src/uiclient/EffectPresentation.cpp).',
    '',
    'import { EffectGuids } from "../effectGuids.js";',
    '',
    '/** An icon the table names: a file in images/icons, without the extension. */',
    `export type PresentationIcon =\n${iconNames(doc).map((name) => `  | ${str(name)}`).join('\n')};`,
    '',
    '/** How one category looks. */',
    'export interface CategoryPresentation {',
    '  /** The name the FX library shows. */',
    '  readonly name: string;',
    '  /** The category colour (CSS). */',
    '  readonly color: string;',
    '  readonly icon: PresentationIcon;',
    '  /** The effect view\'s background gradient, first colour to second (CSS colours). */',
    '  readonly visualBackground?: readonly [string, string];',
    '  /** Stock artwork, relative to core/ui. */',
    '  readonly equipmentImage?: string;',
    '}',
    '',
    '/** How one effect looks, where it differs from its category. */',
    'export interface EffectPresentation {',
    '  readonly icon?: PresentationIcon;',
    '  /** Stock artwork, relative to core/ui. */',
    '  readonly equipmentImage?: string;',
    '}',
    '',
    '/** The FX library\'s categories, in order. */',
    `export const CATEGORY_ORDER: readonly string[] = [\n${(doc.categoryOrder ?? []).map((id) => `  ${str(id)},`).join('\n')}\n];`,
    '',
    '/** Categories folded into another for the effect view\'s background and artwork. */',
    `export const NODE_CATEGORY_ALIASES: Readonly<Record<string, string>> = ${stringMap(doc.nodeCategoryAliases)};`,
    '',
    '/** The chain node\'s colour class for each category. */',
    `export const NODE_CLASSES: Readonly<Record<string, string>> = ${stringMap(doc.nodeClasses)};`,
    '',
    `export const DEFAULT_NODE_CLASS = ${str(doc.defaultNodeClass)};`,
    '',
    `export const DEFAULT_ICON: PresentationIcon = ${str(doc.defaultIcon)};`,
    '',
    '/** The FX library category a blend is listed under, by its gear category. */',
    `export const BLEND_CATEGORIES: Readonly<Record<string, string>> = ${stringMap(doc.blendCategories)};`,
    '',
    `export const DEFAULT_BLEND_CATEGORY = ${str(doc.defaultBlendCategory)};`,
    '',
    `export const CATEGORIES: Readonly<Record<string, CategoryPresentation>> = {\n${Object.entries(doc.categories ?? {})
      .map(([id, entry]) => `  ${str(id)}: ${category(entry)},`).join('\n')}\n};`,
    '',
    '/** By effect type (its EffectGuids value). */',
    `export const EFFECTS: Readonly<Record<string, EffectPresentation>> = {\n${Object.entries(doc.effects ?? {})
      .map(([name, entry]) => `  [EffectGuids.${name}]: ${effect(entry)},`).join('\n')}\n};`,
    '',
    '/** Stock artwork for legacy effect ids a preset may still carry. */',
    `export const LEGACY_EFFECT_EQUIPMENT_IMAGES: Readonly<Record<string, string>> = ${stringMap(doc.legacyEffectEquipmentImages)};`,
    '',
  ];
  return lines.join('\n');
}

/** Whether the module on disk is what the data file generates. */
export function isCurrent(doc) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  return current === generate(doc);
}

function main() {
  if (process.argv.includes('--check')) {
    if (!isCurrent()) {
      console.error('[gen-effect-presentation] core/ui/ts/generated/effectPresentation.ts is out of date with core/ui/data/effect-presentation.json. Run: node tools/gen-effect-presentation.mjs');
      process.exitCode = 1;
    } else {
      console.log('[gen-effect-presentation] OK - the web UI\'s presentation module matches the data file.');
    }
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, generate(), 'utf8');
  console.log(`[gen-effect-presentation] wrote ${path.relative(ROOT, OUT)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
